@app.post("/upload_csv")
async def upload_csv(file: UploadFile = File(...)):
    # Check if it's a CSV file
    if not file.filename.endswith('.csv'):
        return {"error": "Only CSV files are supported."}
    
    # Read CSV content into pandas DataFrame
    contents = await file.read()
    df = pd.read_csv(io.StringIO(contents.decode('utf-8')))
    
    # Check required columns
    if not all(col in df.columns for col in ["lat", "lon"]):
        return {"error": "CSV must contain 'lat' and 'lon' columns."}
    
    # Compute depths
    df["depth"] = df.apply(lambda row: get_depth(row["lat"], row["lon"]), axis=1)

    # Create CSV response in-memory
    output = io.StringIO()
    df.to_csv(output, index=False)
    output.seek(0)

    return StreamingResponse(output, media_type="text/csv", headers={
        "Content-Disposition": "attachment; filename=depth_results.csv"
    })

@app.get("/area_depths_netcdf")
def get_area_depths_netcdf(
    min_lat: float = Query(...),
    max_lat: float = Query(...),
    min_lon: float = Query(...),
    max_lon: float = Query(...),
    step: float = Query(0.1)
):
    if min_lat > max_lat or min_lon > max_lon:
        return {"error": "Minimum values must be less than maximum values."}
    if step <= 0:
        return {"error": "Step must be positive."}

    # Generate lat/lon grid
    lats = np.arange(min_lat, max_lat + step, step)
    lons = np.arange(min_lon, max_lon + step, step)
    lat_grid, lon_grid = np.meshgrid(lats, lons, indexing='ij')

    # Fetch depths
    depths = np.array([[get_depth(lat, lon) for lon in lons] for lat in lats])

    # Create xarray Dataset
    ds = xr.Dataset(
        {
            "elevation": (["lat", "lon"], depths)
        },
        coords={
            "lat": lats,
            "lon": lons
        },
        attrs={
            "title": "GEBCO Water Depth Subset",
            "source": "Generated by FastAPI Server",
            "creator": "Kumars Mahmoodi",
            "email": "kumarsmahmoodi@yahoo.com",
            "page": "https://www.linkedin.com/in/kumars-mahmoodi-17976a150/"
        }
    )

    # Write to temporary NetCDF file
    tmp_file = tempfile.NamedTemporaryFile(delete=False, suffix=".nc")
    ds.to_netcdf(tmp_file.name)
    tmp_file.close()

    return FileResponse(
        tmp_file.name,
        media_type="application/x-netcdf",
        filename="area_depths.nc"
    )

