# Load GEBCO dataset once
bathymetry = xr.open_dataset("GEBCO_2024.nc")

# --- Utility function ---
def get_depth(lat, lon):
    """Find nearest depth value from the dataset."""
    depth = bathymetry['elevation'].sel(lat=lat, lon=lon, method="nearest").values.item()
    return depth

# --- API Endpoints ---

@app.get("/ping")
def ping():
    """Health check endpoint."""
    return {"status": "ok"}

@app.get("/depth")
def read_depth(lat: float, lon: float):
    """Get depth for a single latitude and longitude."""
    try:
        if not (-90 <= lat <= 90):
            raise HTTPException(status_code=400, detail="Latitude must be between -90 and 90.")
        if not (-180 <= lon <= 180):
            raise HTTPException(status_code=400, detail="Longitude must be between -180 and 180.")
        
        depth = get_depth(lat, lon)
        return {"latitude": lat, "longitude": lon, "depth_meters": depth}
    
    except Exception as e:
        return {"error": str(e)}

# Batch request model
class Location(BaseModel):
    lat: float
    lon: float

@app.post("/batch_depths")
def batch_depths(locations: List[Location]):
    """Get depths for multiple locations."""
    results = []
    for loc in locations:
        try:
            if not (-90 <= loc.lat <= 90) or not (-180 <= loc.lon <= 180):
                results.append({
                    "latitude": loc.lat,
                    "longitude": loc.lon,
                    "error": "Invalid latitude or longitude."
                })
                continue
            
            depth = get_depth(loc.lat, loc.lon)
            results.append({
                "latitude": loc.lat,
                "longitude": loc.lon,
                "depth_meters": depth
            })
        except Exception as e:
            results.append({
                "latitude": loc.lat,
                "longitude": loc.lon,
                "error": str(e)
            })
    return results

